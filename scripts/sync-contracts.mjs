#!/usr/bin/env node
// packages/contracts/src is the single source of the API schemas. Each app gets
// a committed copy inside its own Docker build context, so neither the per-app
// lockfiles nor the per-app node_modules volumes have to change. The copies
// resolve `effect` from their host app, which is why the pinned versions must
// match.
//
//   node scripts/sync-contracts.mjs          rewrite the copies
//   node scripts/sync-contracts.mjs --check  fail if a copy or a pin drifted
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/contracts/src';
export const TARGETS = ['backend/src/contracts', 'frontend/app/lib/contracts'];
const PACKAGES = {
  'packages/contracts/package.json': 'devDependencies',
  'backend/package.json': 'dependencies',
  'frontend/package.json': 'dependencies',
};
export const HEADER =
  '// @generated by scripts/sync-contracts.mjs from packages/contracts/src. DO NOT EDIT.\n\n';

function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(full, base);
    return entry.name.endsWith('.ts') ? [path.relative(base, full)] : [];
  });
}

/** What every target directory must contain: relative path → file content. */
export function expectedFiles(rootDir) {
  const sourceDir = path.join(rootDir, SOURCE);
  return new Map(
    listFiles(sourceDir).map(file => [
      file,
      HEADER + readFileSync(path.join(sourceDir, file), 'utf8'),
    ]),
  );
}

export function findProblems(rootDir) {
  const expected = expectedFiles(rootDir);
  const problems = [];

  for (const target of TARGETS) {
    const targetDir = path.join(rootDir, target);
    for (const [file, content] of expected) {
      const full = path.join(targetDir, file);
      if (!existsSync(full)) problems.push(`${target}/${file} is missing`);
      else if (readFileSync(full, 'utf8') !== content) problems.push(`${target}/${file} is stale`);
    }
    for (const file of listFiles(targetDir)) {
      if (!expected.has(file)) problems.push(`${target}/${file} has no source`);
    }
  }

  const pins = Object.entries(PACKAGES).map(([file, field]) => {
    const pkg = JSON.parse(readFileSync(path.join(rootDir, file), 'utf8'));
    return [file, pkg[field]?.effect];
  });
  if (new Set(pins.map(([, version]) => version)).size > 1) {
    problems.push(
      `effect versions differ: ${pins.map(([file, version]) => `${file}=${version}`).join(', ')}`,
    );
  }

  return problems;
}

export function sync(rootDir) {
  const expected = expectedFiles(rootDir);
  for (const target of TARGETS) {
    const targetDir = path.join(rootDir, target);
    for (const file of listFiles(targetDir)) {
      if (!expected.has(file)) rmSync(path.join(targetDir, file));
    }
    for (const [file, content] of expected) {
      const full = path.join(targetDir, file);
      mkdirSync(path.dirname(full), { recursive: true });
      writeFileSync(full, content);
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  if (process.argv.includes('--check')) {
    const problems = findProblems(rootDir);
    if (problems.length > 0) {
      console.error(problems.map(problem => `  ${problem}`).join('\n'));
      console.error('Contracts are out of sync: run `npm run contracts:sync`.');
      process.exit(1);
    }
  } else {
    sync(rootDir);
  }
}
