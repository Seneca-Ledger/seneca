const normalize = (value: string): string =>
  value
    .trim()
    .toLowerCase()
    .replace(/[\u00A0\s]+/g, ' ')
    .replace(/[._-]+/g, ' ')
    .replace(/[()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/**
 * The brand mark for a vendor name, or null when no bundled mark matches.
 * Matching is by substring, so "Netflix Premium Family" still finds Netflix.
 */
export const resolveVendorIcon = (vendorName?: string | null): VendorIcon | null => {
  if (!vendorName) {
    return null;
  }

  const name = normalize(vendorName);
  for (const [keyword, slug] of KEYWORDS) {
    if (name.includes(keyword)) {
      return ICONS[slug] ?? null;
    }
  }
  return null;
};
