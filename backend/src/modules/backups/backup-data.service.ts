import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { Injectable, Optional } from '@nestjs/common';
import { InjectDataSource } from '@nestjs/typeorm';
import { type DataSource, type EntityMetadata, In } from 'typeorm';
import { FileStorageService } from '../../common/services/file-storage.service';
import type { Statement } from '../../entities';

export const EXCLUDED_TABLES = new Set([
  'api_keys',
  'auth_sessions',
  'backup_configurations',
  'backup_runs',
  'idempotency_keys',
  'import_sessions',
  'integration_tokens',
  'integrations',
  'open_protocol_settings',
  // The access point's API key and secret: reconnected after a restore, like the other integrations.
  'peppol_connections',
  // The access point's API key and secret: reconnected after a restore, like the other integrations.
  'peppol_connections',
  'notifications',
  'report_history',
  'webhook_deliveries',
  'webhook_endpoints',
  'webhook_subscriptions',
  // People and per-member rows, not workspace data: a restore makes its own owner membership.
  'users',
  'workspace_invitations',
  'workspace_members',
  // Derived and regenerated by the insight job.
  'insights',
  // The workspace's own past versions: a snapshot does not hold the list of snapshots.
  'workspace_versions',
  // Useless without the token this backup strips: recreated, not restored.
  'custom_table_shares',
]);

export const SENSITIVE_PROPERTIES = new Set([
  'accessToken',
  'encryptedSecrets',
  'passwordHash',
  'refreshToken',
  'secret',
  'token',
]);

/**
 * Columns hidden from ordinary reads (`select: false`) that a backup still has
 * to carry, by table: without them the rows cannot be restored.
 */
const HIDDEN_COLUMNS_IN_BACKUP: Record<string, string[]> = {
  // The XML exactly as it went over Peppol (NOT NULL); the log means nothing without it.
  peppol_transmissions: ['documentXml'],
  // The documents as issued and sent: a restored invoice reopens the same PDF.
  invoices: ['fileData'],
  credit_notes: ['fileData'],
};

/**
 * Rows without a workspace column of their own, collected by their parent
 * row: `column` of `table` holds the id of a row of `parent`. In order, since
 * a parent can be a related collection itself. Without them a restored
 * invoice has no lines and a journal entry is refused for having none. Join
 * tables name their columns as in the database.
 */
export const RELATED_COLLECTIONS: ReadonlyArray<{ table: string; column: string; parent: string }> =
  [
    { table: 'custom_table_columns', column: 'tableId', parent: 'custom_tables' },
    { table: 'custom_table_rows', column: 'tableId', parent: 'custom_tables' },
    { table: 'custom_table_column_styles', column: 'tableId', parent: 'custom_tables' },
    { table: 'custom_table_cell_styles', column: 'rowId', parent: 'custom_table_rows' },
    { table: 'file_versions', column: 'statementId', parent: 'statements' },
    { table: 'invoice_line_items', column: 'invoiceId', parent: 'invoices' },
    { table: 'credit_note_line_items', column: 'creditNoteId', parent: 'credit_notes' },
    { table: 'journal_lines', column: 'entryId', parent: 'journal_entries' },
    { table: 'statement_tags', column: 'statement_id', parent: 'statements' },
    { table: 'transaction_tags', column: 'transaction_id', parent: 'transactions' },
    { table: 'receipt_tags', column: 'receipt_id', parent: 'receipts' },
    { table: 'payable_tags', column: 'payable_id', parent: 'payables' },
  ];

export const isWorkspaceScoped = (metadata: EntityMetadata): boolean =>
  metadata.columns.some(column => column.propertyName === 'workspaceId');

type BackupSnapshotData = {
  collections: Record<string, unknown[]>;
  files: Array<{ path: string; contents: Buffer }>;
};

@Injectable()
export class BackupDataService {
  constructor(
    @InjectDataSource() private readonly dataSource: DataSource,
    @Optional() private readonly fileStorageService?: FileStorageService,
  ) {}

  async collect(workspaceId: string): Promise<BackupSnapshotData> {
    const collections: Record<string, unknown[]> = {};
    const files: Array<{ path: string; contents: Buffer }> = [];
    for (const metadata of this.dataSource.entityMetadatas) {
      if (!isWorkspaceScoped(metadata) || EXCLUDED_TABLES.has(metadata.tableName)) continue;
      const repository = this.dataSource.getRepository(metadata.target);
      const rows = await repository.find({
        where: { workspaceId } as never,
        order: this.byPrimaryKey(metadata),
        ...this.selectFor(metadata),
      });
      const records = rows.map(row => this.toBackupRecord(metadata, row));
      collections[metadata.tableName] = records;
      if (metadata.tableName === 'statements' && this.fileStorageService) {
        await this.collectStatementFiles(rows as Statement[], records, files);
      }
      if (metadata.tableName === 'receipts') {
        await this.collectReceiptAttachments(records, files);
      }
    }
    await this.collectRelatedCollections(collections);
    return { collections, files };
  }

  /** The usual columns, plus the hidden ones this table's backup needs. */
  private selectFor(metadata: EntityMetadata): { select?: never } {
    const hidden = HIDDEN_COLUMNS_IN_BACKUP[metadata.tableName];
    if (!hidden) {
      return {};
    }
    const columns = metadata.columns.filter(
      column => column.isSelect || hidden.includes(column.propertyName),
    );
    return {
      select: Object.fromEntries(columns.map(column => [column.propertyName, true])) as never,
    };
  }

  /**
   * Rows in a fixed order, so the same data always makes the same snapshot:
   * a workspace version taken on a day with no changes is recognised by its hash.
   */
  private byPrimaryKey(metadata: EntityMetadata): never {
    return Object.fromEntries(
      metadata.primaryColumns.map(column => [column.propertyName, 'ASC']),
    ) as never;
  }

  private toBackupRecord(metadata: EntityMetadata, row: unknown): Record<string, unknown> {
    const source = row as Record<string, unknown>;
    return metadata.columns.reduce<Record<string, unknown>>((record, column) => {
      const propertyName = column.propertyName;
      const value = source[propertyName];
      if (!SENSITIVE_PROPERTIES.has(propertyName) && value !== undefined) {
        // Binary columns (stored PDFs, file versions) travel as base64 inside the JSON.
        record[propertyName] = Buffer.isBuffer(value)
          ? { encoding: 'base64', value: value.toString('base64') }
          : value;
      }
      return record;
    }, {});
  }

  private async collectStatementFiles(
    statements: Statement[],
    records: Record<string, unknown>[],
    files: Array<{ path: string; contents: Buffer }>,
  ): Promise<void> {
    const recordsById = new Map(records.map(record => [record.id, record]));
    for (const statement of statements) {
      const file = await this.fileStorageService?.getStatementFileStream(statement);
      if (!file) continue;
      const contents = await this.streamToBuffer(file.stream);
      const safeFileName = path.posix.basename(file.fileName);
      const backupPath = `statements/${statement.id}/${safeFileName}`;
      const record = recordsById.get(statement.id);
      if (record) record.filePath = backupPath;
      files.push({ path: backupPath, contents });
    }
  }

  private async streamToBuffer(stream: NodeJS.ReadableStream): Promise<Buffer> {
    const chunks: Buffer[] = [];
    for await (const chunk of stream) {
      chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
    }
    return Buffer.concat(chunks);
  }

  private async collectReceiptAttachments(
    records: Record<string, unknown>[],
    files: Array<{ path: string; contents: Buffer }>,
  ): Promise<void> {
    for (const record of records) {
      const paths = Array.isArray(record.attachmentPaths) ? record.attachmentPaths : [];
      const portablePaths: string[] = [];
      for (const [index, sourcePath] of paths.entries()) {
        if (typeof sourcePath !== 'string') continue;
        const safeName = path.posix.basename(sourcePath);
        const backupPath = `receipts/${record.id}/${index}-${safeName}`;
        files.push({ path: backupPath, contents: await fs.readFile(sourcePath) });
        portablePaths.push(backupPath);
      }
      record.attachmentPaths = portablePaths;
    }
  }

  private async collectRelatedCollections(collections: Record<string, unknown[]>): Promise<void> {
    for (const { table, column, parent } of RELATED_COLLECTIONS) {
      await this.collectByReference(table, column, this.ids(collections[parent]), collections);
    }
  }

  private async collectByReference(
    tableName: string,
    propertyName: string,
    ids: string[],
    collections: Record<string, unknown[]>,
  ): Promise<void> {
    const metadata = this.dataSource.entityMetadatas.find(item => item.tableName === tableName);
    if (!metadata || ids.length === 0) return;
    // A join table has no entity to find through; its columns keep their database names.
    const rows: unknown[] = metadata.isJunction
      ? await this.dataSource.query(
          `SELECT * FROM "${metadata.tableName}" WHERE "${propertyName}" = ANY($1::uuid[]) ORDER BY 1, 2`,
          [ids],
        )
      : await this.dataSource.getRepository(metadata.target).find({
          where: { [propertyName]: In(ids) } as never,
          order: this.byPrimaryKey(metadata),
        });
    collections[tableName] = rows.map(row => this.toBackupRecord(metadata, row));
  }

  private ids(records: unknown[] | undefined): string[] {
    return (records || [])
      .map(record => (record as Record<string, unknown>).id)
      .filter((id): id is string => typeof id === 'string');
  }
}
