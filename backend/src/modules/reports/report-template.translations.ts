/**
 * The title key of each template, so a subject line or a list can name a
 * template in the reader's language. The balance sheet is absent on purpose:
 * its title comes from BalanceService, with the chart of accounts.
 */
const TITLE_KEYS: Record<string, TemplateLabelKey> = {
  pnl: 'titlePnl',
  'cash-flow': 'titleCashFlow',
  'expense-by-category': 'titleExpenseByCategory',
  'transaction-register': 'titleTransactionRegister',
  'monthly-summary': 'titleMonthlySummary',
  'category-by-month': 'titleCategoryByMonth',
  'budget-vs-actual': 'titleBudgetVsActual',
  'investment-holdings': 'titleInvestmentHoldings',
};

/** The template's name in `locale`, or null for one this dictionary cannot name. */
export function templateTitle(
  templateId: string,
  locale: string | null | undefined,
): string | null {
  const key = TITLE_KEYS[templateId];
  return key ? renderTemplateLabels(locale)[key] : null;
}

/** Falls back to English for a locale the templates do not carry. */
export function renderTemplateLabels(locale: string | null | undefined): TemplateLabelMap {
  return TEMPLATE_LABELS[locale ?? ''] ?? TEMPLATE_LABELS.en;
}

/** `{{name}}` placeholders filled in; a value that is absent is left alone. */
export function fillLabel(template: string, values: Record<string, string | number>): string {
  return template.replace(/{{(\w+)}}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}
