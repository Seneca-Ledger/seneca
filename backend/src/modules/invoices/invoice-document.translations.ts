/** Labels for a locale tag such as `de`, `pt-BR` or an unknown one. */
export function renderInvoiceLabels(locale: string | null | undefined): InvoiceLabelMap {
  const base = String(locale ?? '')
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];
  return { ...en, ...(OVERRIDES[base] ?? {}) };
}
