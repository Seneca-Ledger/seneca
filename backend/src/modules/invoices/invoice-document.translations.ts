/**
 * Labels on the invoice document.
 *
 * The thirteen table and date labels are the ones the invoices screen already
 * ships in every locale; the rest — the issuer block, the payment block and the
 * reverse-charge wording — are written here for the locales the product
 * translates its documents into. Anything missing falls back to English per
 * key, so a locale never loses the labels it does have.
 */
